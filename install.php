<?php
/**
 * Web installer – runs once from the browser (no terminal needed).
 * After a successful install it locks itself; delete this file afterwards.
 */
define('ROOT', __DIR__);
define('APP', ROOT . '/app');
define('APP_VERSION', 'install');

header('Content-Type: text/html; charset=utf-8');
header('X-Robots-Tag: noindex');

$installed = is_file(APP . '/config.php');

function h($s) { return htmlspecialchars((string)$s, ENT_QUOTES, 'UTF-8'); }

$checks = [
    ['PHP نسخه ۷.۴ یا بالاتر', version_compare(PHP_VERSION, '7.4.0', '>='), PHP_VERSION],
    ['افزونه PDO MySQL', extension_loaded('pdo_mysql'), ''],
    ['افزونه mbstring', extension_loaded('mbstring'), ''],
    ['افزونه JSON', function_exists('json_encode'), ''],
    ['افزونه cURL (برای پیامک و درگاه)', function_exists('curl_init'), function_exists('curl_init') ? '' : 'در نبود cURL از روش جایگزین استفاده می‌شود'],
    ['پوشه app قابل نوشتن', is_writable(APP), ''],
    ['پوشه storage قابل نوشتن', is_writable(ROOT . '/storage'), ''],
    ['پوشه assets/cache قابل نوشتن', is_writable(ROOT . '/assets/cache'), ''],
    ['پوشه uploads قابل نوشتن', is_writable(ROOT . '/uploads'), ''],
];
$ok = true;
foreach ($checks as $c) if (!$c[1] && strpos($c[0], 'cURL') === false) $ok = false;

$https = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') || (isset($_SERVER['HTTP_X_FORWARDED_PROTO']) && $_SERVER['HTTP_X_FORWARDED_PROTO'] === 'https');
$host = isset($_SERVER['HTTP_HOST']) ? $_SERVER['HTTP_HOST'] : 'localhost';
$dir = rtrim(str_replace('\\', '/', dirname($_SERVER['SCRIPT_NAME'])), '/');
$baseGuess = ($https ? 'https' : 'http') . '://' . $host . $dir;

$error = '';
$done = false;

if (!$installed && $_SERVER['REQUEST_METHOD'] === 'POST' && $ok) {
    $db = [
        'host' => trim($_POST['db_host']) ?: 'localhost',
        'port' => trim($_POST['db_port']),
        'name' => trim($_POST['db_name']),
        'user' => trim($_POST['db_user']),
        'pass' => (string)$_POST['db_pass'],
    ];
    $adminUser = preg_replace('/[^a-zA-Z0-9_.-]/', '', $_POST['admin_user']);
    $adminPass = (string)$_POST['admin_pass'];
    $baseUrl = rtrim(trim($_POST['base_url']), '/');
    if ($adminUser === '' || strlen($adminPass) < 8) {
        $error = 'نام کاربری مدیر (لاتین) و رمز حداقل ۸ کاراکتری لازم است.';
    } elseif (!preg_match('#^https?://#', $baseUrl)) {
        $error = 'آدرس سایت باید با http:// یا https:// شروع شود.';
    } else {
        try {
            $dsn = 'mysql:host=' . $db['host'] . ($db['port'] ? ';port=' . $db['port'] : '') . ';dbname=' . $db['name'] . ';charset=utf8mb4';
            $pdo = new PDO($dsn, $db['user'], $db['pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
            $exists = $pdo->query("SHOW TABLES LIKE 'seats'")->fetchColumn();
            if ($exists) throw new Exception('جداول برنامه از قبل در این دیتابیس وجود دارند. یک دیتابیس خالی انتخاب کنید.');
            $sql = file_get_contents(ROOT . '/database/schema.sql');
            foreach (preg_split('/;\s*\n/', $sql) as $stmt) {
                $stmt = trim(preg_replace('/^--.*$/m', '', $stmt));
                if ($stmt !== '') $pdo->exec($stmt);
            }
            $config = [
                'db' => $db,
                'base_url' => $baseUrl,
                'pretty_urls' => isset($_POST['pretty']) && $_POST['pretty'] === '1',
                'app_key' => bin2hex(random_bytes(32)),
                'debug' => false,
            ];
            foreach (['storage/cache', 'storage/logs', 'storage/sessions'] as $d) {
                if (!is_dir(ROOT . '/' . $d)) @mkdir(ROOT . '/' . $d, 0755, true);
            }
            // boot the app with the new config to seed data
            $GLOBALS['config'] = $config;
            date_default_timezone_set('Asia/Tehran');
            require APP . '/lib/helpers.php';
            require APP . '/lib/db.php';
            require APP . '/lib/jdate.php';
            require APP . '/lib/seed.php';
            db_tx(function () use ($adminUser, $adminPass) {
                seed_all();
                db_insert('admins', ['username' => $adminUser, 'password_hash' => password_hash($adminPass, PASSWORD_DEFAULT), 'name' => 'مدیر سیستم', 'role' => 'admin', 'is_active' => 1, 'created_at' => now()]);
            });
            if (@file_put_contents(APP . '/config.php', "<?php\n// Generated by installer " . date('Y-m-d H:i') . "\nreturn " . var_export($config, true) . ";\n") === false) {
                throw new Exception('نوشتن فایل app/config.php ممکن نشد. دسترسی پوشه app را بررسی کنید.');
            }
            @unlink(ROOT . '/storage/cache/settings.php');
            $done = true;
            $installed = true;
        } catch (Throwable $e) {
            $error = $e->getMessage();
        }
    }
}
