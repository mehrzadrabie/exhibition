        <li>کاربران پنل ← برای نیروهای پذیرش حساب «کنترل ورود» بسازید</li>
      </ol>
      <div class="row"><a class="btn" href="<?= h($dir) ?>/<?= !empty($config['pretty_urls']) ? 'admin' : 'index.php?r=/admin' ?>">ورود به پنل مدیریت</a>
      <a class="btn ghost" href="<?= h($dir) ?>/">مشاهده سایت</a></div>
    </div>
  <?php elseif ($installed): ?>
    <div class="alert info">سامانه قبلاً نصب شده است. برای نصب مجدد، فایل app/config.php را حذف کنید. فایل install.php را پاک کنید.</div>
  <?php else: ?>
    <div class="card">
      <h3>بررسی پیش‌نیازها</h3>
      <table class="t">
        <?php foreach ($checks as $c): ?>
        <tr><td><?= h($c[0]) ?></td><td><?= $c[1] ? '<span class="badge ok">✔</span>' : '<span class="badge bad">✖</span>' ?> <span class="small muted"><?= h($c[2]) ?></span></td></tr>
        <?php endforeach ?>
      </table>
      <?php if (!$ok): ?><div class="alert err mt">ابتدا موارد قرمز را رفع کنید (معمولاً دسترسی پوشه‌ها را از فایل‌منیجر هاست روی 755 بگذارید).</div><?php endif ?>
    </div>
    <?php if ($error): ?><div class="alert err"><?= h($error) ?></div><?php endif ?>
    <form method="post" class="card">
      <h3>اطلاعات دیتابیس MySQL</h3>
      <p class="small muted">از بخش MySQL Databases در cPanel / DirectAdmin یک دیتابیس و کاربر بسازید و کاربر را با همه دسترسی‌ها به دیتابیس متصل کنید.</p>
      <div class="grid g2">
        <div class="field"><label>نام دیتابیس</label><input type="text" name="db_name" class="input-ltr" required value="<?= h(isset($_POST['db_name']) ? $_POST['db_name'] : '') ?>"></div>
        <div class="field"><label>نام کاربری دیتابیس</label><input type="text" name="db_user" class="input-ltr" required value="<?= h(isset($_POST['db_user']) ? $_POST['db_user'] : '') ?>"></div>
        <div class="field"><label>رمز دیتابیس</label><input type="password" name="db_pass" class="input-ltr"></div>
        <div class="field"><label>هاست دیتابیس</label><input type="text" name="db_host" class="input-ltr" value="<?= h(isset($_POST['db_host']) ? $_POST['db_host'] : 'localhost') ?>"></div>
        <div class="field"><label>پورت (اختیاری)</label><input type="text" name="db_port" class="input-ltr" value="<?= h(isset($_POST['db_port']) ? $_POST['db_port'] : '') ?>"></div>
      </div>
      <h3 class="mt">سایت و مدیر</h3>
      <div class="field"><label>آدرس سایت</label><input type="text" name="base_url" class="input-ltr" value="<?= h(isset($_POST['base_url']) ? $_POST['base_url'] : $baseGuess) ?>">
        <div class="help">حتماً با https باشد (برای درگاه پرداخت و دوربین اسکنر لازم است).</div></div>
      <div class="grid g2">
        <div class="field"><label>نام کاربری مدیر</label><input type="text" name="admin_user" class="input-ltr" required value="admin"></div>
        <div class="field"><label>رمز مدیر (حداقل ۸)</label><input type="password" name="admin_pass" class="input-ltr" required></div>
      </div>
      <input type="hidden" name="pretty" id="pretty" value="0">
      <p class="small muted" id="rw">در حال بررسی پشتیبانی از آدرس‌های تمیز…</p>
      <button class="btn lg block" type="submit" <?= $ok ? '' : 'disabled' ?>>نصب</button>
    </form>
    <script>
      fetch('__rewrite_test', {cache: 'no-store'}).then(function (r) { return r.ok ? r.text() : ''; }).then(function (t) {
        var ok = t.trim() === 'ok';
        document.getElementById('pretty').value = ok ? '1' : '0';
        document.getElementById('rw').textContent = ok ? '✔ آدرس‌های تمیز (mod_rewrite) فعال است.' : 'آدرس‌های تمیز در دسترس نیست؛ از آدرس‌های index.php?r= استفاده می‌شود (مشکلی ایجاد نمی‌کند).';
      }).catch(function () {});
    </script>
  <?php endif ?>
